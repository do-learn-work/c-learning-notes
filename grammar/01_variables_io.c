/* ================================================================
 * 一、数据类型（C 是「强类型语言」，变量必须先声明类型再用）
 * ================================================================
 *
 * 【整数类型】
 *   char    1 字节   字符/小整数（-128~127 或 0~255）
 *   short   2 字节   短整数
 *   int     4 字节   常用整数（-2^31 ~ 2^31-1）  ← 刷题默认用这个
 *   long    4/8 字节 长整数（Windows 上 4 字节，Linux 上 8 字节）
 *   long long 8 字节 超长整数（-2^63 ~ 2^63-1）  ← 超大数用这个
 *
 * 【浮点类型】
 *   float   4 字节   单精度（约 6 位有效数字）
 *   double  8 字节   双精度（约 15-17 位有效数字）  ← 刷题默认用这个
 *   long double  扩展精度
 *
 * 【修饰符】（加在整数类型前面）
 *   signed   有符号（默认，可省略）
 *   unsigned 无符号（只能存 0 和正数，范围翻倍）
 */

void demo_data_types(void)
{
    printf("=== 数据类型大小 ===\n");
    printf("int       = %zu 字节, 范围 [%d, %d]\n",
           sizeof(int), INT_MIN, INT_MAX);
    printf("long long = %zu 字节, 范围 [%lld, %lld]\n",
           sizeof(long long), LLONG_MIN, LLONG_MAX);
    printf("float     = %zu 字节, 精度约 6 位\n", sizeof(float));
    printf("double    = %zu 字节, 精度约 15 位\n", sizeof(double));

    /* 声明 + 初始化（推荐） */
    int a = 42;
    double pi = 3.141592653589793;
    char grade = 'A';
    unsigned int positive = 100;
    long long big = 9223372036854775807LL;

    /* 声明但不初始化（C 语言不自动清零！值是随机垃圾！） */
    int uninitialized;
    printf("未初始化变量（别用！）= %d\n", uninitialized); // 输出随机数

    /* 【坑点】整数溢出 */
    int overflow = INT_MAX + 1; // 超出范围 → 变成 INT_MIN（环绕）
    printf("INT_MAX + 1 = %d (溢出了！)\n", overflow);
    /* 【刷题关联】如果题目说"结果可能很大"，把 int 改成 long long！ */
}

/* ================================================================
 * 二、变量命名规则
 * ================================================================
 * ✅ 合法：字母/数字/_ 组成，**不能以数字开头**，区分大小写
 *    例：num, total_students, _count, x1
 * ❌ 非法：1abc（数字开头）、int（关键字）、a b（空格）
 *
 * 【风格】C 语言默认用 snake_case（小写+下划线）
 *    例：max_value, student_score  ← 推荐
 *    例：maxValue, studentScore    ← 也能编译（驼峰，C++/Java 常用）
 */

void demo_naming(void)
{
    int student_count = 30; // snake_case（C 主流）
    int studentCount = 30;  // 驼峰（也能用）
    printf("两种命名都合法：%d %d\n", student_count, studentCount);
}

/* ================================================================
 * 三、运算符（按优先级从高到低）
 * ================================================================
 *
 * 【算术运算符】  +  -  *  /  %  ++  --
 *   /   整数除法直接砍小数：5/2 = 2  （如果要保留小数，至少一个操作数是浮点）
 *   %   取模（求余）：5%2 = 1  （只能用于整数！）
 *   ++  自增：a++ 和 ++a 的区别
 *   --  自减：同理
 *
 * 【关系运算符】  >  <  >=  <=  ==  !=
 *   结果是 0（假）或 1（真），C 语言没有布尔类型（C99 有 _Bool）
 *
 * 【逻辑运算符】  &&  ||  !
 *   && 短路与：左边假 → 右边不执行
 *   || 短路或：左边真 → 右边不执行
 *
 * 【赋值运算符】  =  +=  -=  *=  /=  %=
 *
 * 【位运算符】（刷题进阶会用到）  &  |  ^  ~  <<  >>
 */

void demo_operators(void)
{
    printf("=== 运算符 ===\n");

    /* 算术 */
    int a = 5, b = 2;
    printf("5 + 2 = %d\n", a + b);                  // 7
    printf("5 / 2 = %d (整数除法！)\n", a / b);     // 2（不是 2.5！）
    printf("5.0 / 2 = %.1f (浮点除法)\n", 5.0 / 2); // 2.5
    printf("5 %% 2 = %d (取模)\n", a % b);          // 1
    /* 【坑点】整数除法和浮点除法的区别！刷题时经常踩 */

    /* 自增自减：a++ vs ++a
     * 后置++：表达式取「自增前」的值，之后变量 +1
     * 前置++：变量先 +1，表达式取「自增后」的值
     *
     * 【坑点】千万别写成 printf("%d %d", x, x++);
     *   同一个表达式里既读 x 又改 x，求值顺序未定义（gcc 会告警
     *   -Wsequence-point），换编译器或开 -O2 结果可能就变了。
     *   正确做法：先把自增结果存进变量，再打印。
     */
    int x = 5;
    int x_before = x++; /* x_before = 5，之后 x = 6 */
    printf("x 初始 = 5, x++ 的值 = %d, 之后 x = %d\n", x_before, x);

    int y = 5;
    int y_after = ++y; /* y 先变成 6，y_after = 6 */
    printf("y 初始 = 5, ++y 的值 = %d, 之后 y = %d\n", y_after, y);

    /* 关系 */
    printf("5 > 3 = %d (1=真)\n", 5 > 3);   // 1
    printf("5 == 3 = %d (0=假)\n", 5 == 3); // 0
    /* 【坑点】别把 == 写成 =！
     *   if (n = 5)   → 赋值语句，永远为真！（编译器可能警告）
     *   if (n == 5)  → 正确的比较
     */

    /* 逻辑 */
    int n = 7;
    printf("n>0 && n<10 = %d\n", n > 0 && n < 10); // 1
    printf("n<0 || n>10 = %d\n", n < 0 || n > 10); // 0
    /* 短路特性演示 */
    int i = 0;
    (1 == 0) && (i = 100); // 左边假 → 右边不执行，i 还是 0
    printf("短路测试：i = %d (没被赋值)\n", i);
}

/* ================================================================
 * 四、格式化输出 printf（刷题最常用的输出函数）
 * ================================================================
 *
 * 【格式串模板】  %[标志][宽度][.精度]类型
 *
 * 常用类型符：
 *   %d   有符号十进制整数（int）
 *   %lld 有符号十进制整数（long long）
 *   %u   无符号十进制整数
 *   %f   浮点数（默认 6 位小数）
 *   %c   字符
 *   %s   字符串（char 数组）
 *   %p   指针（地址）
 *   %zu  sizeof 的返回值类型（size_t）  ← 打印 sizeof 结果用这个！
 *   %x   十六进制整数（小写）
 *   %o   八进制整数
 *   %%   输出一个 %
 *
 * 精度修饰：
 *   %.3f   保留 3 位小数（四舍五入）
 *   %.5s   只打印字符串前 5 个字符
 *
 * 宽度 + 对齐：
 *   %10d   宽度 10，右对齐，左边补空格
 *   %-10d  宽度 10，左对齐
 *   %010d  宽度 10，左边补 0
 */

void demo_printf(void)
{
    printf("=== printf ===\n");

    /* 基础用法 */
    int age = 20;
    double score = 92.3456;
    char grade = 'A';
    printf("年龄：%d, 成绩：%.2f, 等级：%c\n", age, score, grade);
    /* 输出：年龄：20, 成绩：92.35, 等级：A  （%.2f 四舍五入） */

    /* 宽度对齐（做表格时有用） */
    printf("%-10s %10s\n", "姓名", "分数"); // 左对齐名字，右对齐分数
    printf("%-10s %10.2f\n", "张三", 85.5);
    printf("%-10s %10.2f\n", "李四", 92.0);
    /* 输出：
     * 姓名            分数
     * 张三           85.50
     * 李四           92.00
     */

    /* 打印 sizeof 结果必须用 %zu（或 %u 强转） */
    printf("sizeof(int) = %zu\n", sizeof(int));
    /* 【坑点】用 %d 打印 sizeof 结果会触发未定义行为！ */
}

/* ================================================================
 * 五、格式化输入 scanf（刷题读入必用）
 * ================================================================
 *
 * 【和 printf 的关键区别】
 *   scanf 必须传「变量的地址」，用 & 取地址符！
 *
 * 常用格式符（和 printf 几乎一样，但浮点有区别）：
 *   %d    读 int
 *   %lld  读 long long
 *   %u    读 unsigned int
 *   %lf   读 double  ← 注意！printf 用 %f，scanf 用 %lf！
 *   %f    读 float
 *   %c    读字符（会读空格和换行！要用 %1c 或 " %c" 跳过空白）
 *   %s    读字符串（遇到空格/换行停止，不需要 &，数组名本身就是地址）
 *
 * 输入分隔符：
 *   scanf("%d %d", &a, &b)  → 空格、Tab、换行都能分隔
 *   scanf("%d,%d", &a, &b)  → 必须用逗号分隔（格式串里的逗号要原样输入）
 */

void demo_scanf(void)
{
    printf("=== scanf ===\n");

    /* 整数输入 */
    int a, b;
    printf("请输入两个整数（空格/回车分隔）：");
    /* scanf("%d %d", &a, &b); */
    /* printf("a=%d, b=%d\n", a, b); */

    /* 【坑点】scanf 的 & 不能漏！
     *   scanf("%d", a);   ← 错！a 是 int，不是地址
     *   scanf("%d", &a);  ← 对！传 a 的地址
     */

    /* 浮点输入：double 必须用 %lf */
    double f;
    /* scanf("%lf", &f);  ← 对
     * scanf("%f", &f);   ← 错！读 double 用 %lf，读 float 才用 %f
     */

    /* 字符输入：%c 会读空白字符 */
    char c1, c2;
    /* 假设输入：A B（中间有空格）
     * scanf("%c %c", &c1, &c2);  → c1='A', c2='B' （格式串里的空格跳过空白）
     * scanf("%c%c", &c1, &c2);   → c1='A', c2=' ' （把空格也读进去了！）
     */

    /* 字符串输入：数组名本身就是地址，不需要 & */
    char name[32];
    /* scanf("%31s", name);  ← %31s 限制最多读 31 字符（留 1 位给 '\0'），防溢出
     * scanf("%s", &name);   ← 错！name 本身就是地址，不用 &
     */
}

/* ================================================================
 * 六、类型转换
 * ================================================================
 *
 * 【隐式转换】（自动发生）
 *   int + double → double    小类型自动提升为大类型
 *   赋值时：大类型 → 小类型可能丢精度（编译器警告）
 *     double d = 3.14; int i = d;  → i = 3（砍掉小数部分）
 *
 * 【显式转换】（强制类型转换）  (类型)值
 *   (int)3.7    → 3
 *   (double)5   → 5.0
 *   (char)65    → 'A'
 */

void demo_cast(void)
{
    printf("=== 类型转换 ===\n");

    int a = 5, b = 2;
    printf("整数除法：%d / %d = %d\n", a, b, a / b);
    printf("显式转浮点：(double)%d / %d = %.2f\n", a, b, (double)a / b);
    /* (double)a / b  → 先把 a 转成 double，然后 b 也自动提升 → 浮点除法
     * (double)(a / b) → 先做整数除法得 2，再转 double → 2.00（没用！）
     */
}

int main(void)
{
    init_utf8_console(); /* 让中文正常显示（详见 utf8_console.h） */
    demo_data_types();
    printf("\n");
    demo_naming();
    printf("\n");
    demo_operators();
    printf("\n");
    demo_printf();
    printf("\n");
    demo_scanf();
    printf("\n");
    demo_cast();
    return 0;
}